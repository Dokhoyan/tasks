package main

//Нужно отправить числа nums в out по порядку и вернуться после последней отправки. out открыт
//и остается у вызывающей стороны - нельзя закрывать его; получатель работает параллельно.
//nums нельзя менять.

func SendAll(nums []int, out chan<- int) {
	for _, n := range nums {
		out <- n
	}
}
